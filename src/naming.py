"""Единая точка сборки и разбора имён файлов Umbra.

Метка идёт ПЕРЕД именем документа: '[ANON] Договор.docx'. В алфавитном списке
папки такие файлы собираются вместе рядом с оригиналом, а не расползаются по
всей папке, как это было с суффиксами ('Договор [ANON].docx').

Разбор намеренно понимает ОБЕ формы — и префиксную, и старую суффиксную.
Файлы, созданные прежними версиями Umbra, продолжают находиться: иначе паспорт
к ним не подобрался бы и восстановление падало бы с «Не найден паспорт
обезличивания», что читается как «оригинал подменили», а не как смена схемы имён.

Никакой модуль не должен собирать эти имена f-строкой сам: раньше сборка жила в
трёх местах, а разбор — в четырнадцати, и любая правка схемы означала охоту по
всей кодовой базе.
"""

import re

ANON = '[ANON]'      # обезличенный документ — его юрист отдаёт ИИ
ANSWER = '[ОТВЕТ]'   # ответ ИИ, сохранённый юристом вручную (мы его не создаём)
RESULT = '[UMBRA]'   # итог: данные восстановлены, документ готов

MARKERS = (ANON, ANSWER, RESULT)

# Метки прежних версий. Только для разбора — новых файлов с ними не создаём.
LEGACY_MARKERS = ('[DEANON]',)

_STRIP_RE = re.compile(
    r'\s*(?:' + '|'.join(re.escape(m) for m in MARKERS + LEGACY_MARKERS) + r')\s*',
    re.IGNORECASE,
)


def strip_markers(stem):
    """Убирает все метки Umbra из основы имени, в любой позиции.

    '[ANON] Договор' → 'Договор'; 'Договор [ANON]' → 'Договор' (старая схема).
    """
    return _STRIP_RE.sub(' ', stem).strip()


def has_marker(stem, marker):
    """Есть ли метка в основе имени — независимо от позиции и регистра.

    Проверять нужно ИМЕННО основу имени, а не полный путь: папка
    'C:\\Мои [ANON] дела\\' иначе выдаёт себя за помеченный файл.
    """
    return marker.lower() in stem.lower()


def has_any_marker(stem):
    return any(has_marker(stem, marker) for marker in MARKERS + LEGACY_MARKERS)


def build_name(stem, marker, ext):
    """Собирает имя файла с меткой впереди: ('Договор', ANON, '.docx')
    → '[ANON] Договор.docx'. Прежние метки из основы вычищаются, чтобы не
    накапливать '[UMBRA] [ANON] Договор'."""
    return f'{marker} {strip_markers(stem)}{ext}'
